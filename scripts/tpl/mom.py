"""MOM — Minutes of Meeting (FRM.IT.015).
.venv/bin/python scripts/tpl/mom.py <BMSS-MOM-01-HOJAKARTA-V-2026.docx>  -> templates/mom.docx

Multi-line texts (Peserta, Poin Pembahasan) are a loop over lines: each line is printed either as a
plain paragraph or, when it starts with "-", as the original "- " list paragraph (Word numbering),
so the indented look of the original is kept.
The signature table is generated by the app ({@ttd} raw OOXML) so the parties/columns are editable.
"""
import copy
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from docx.oxml.ns import qn
from docx.text.paragraph import Paragraph
from lib import _runs, main_args, open_doc, row_loop, save, set_cell, set_text

src, *rest = main_args()
out = rest[0] if rest else "templates/mom.docx"
d = open_doc(src)


def clone_par(p: Paragraph, text: str) -> Paragraph:
    """Detached copy of `p` (paragraph + first-run formatting) holding `text`."""
    el = copy.deepcopy(p._p)
    np = Paragraph(el, p._parent)
    set_text(np, text)
    return np


def lines_block(cell, loop: str, plain: Paragraph, bullet: Paragraph, tail: str = "") -> None:
    """Replace the cell content with a paragraph loop over `loop` = [{text, bullet}]."""
    plain_t, bullet_t = plain, bullet
    pars = [
        clone_par(plain_t, "{#" + loop + "}"),
        clone_par(plain_t, "{#bullet}"),
        clone_par(bullet_t, "{text}"),
        clone_par(plain_t, "{/bullet}"),
        clone_par(plain_t, "{^bullet}"),
        clone_par(plain_t, "{text}"),
        clone_par(plain_t, "{/bullet}"),
        clone_par(plain_t, "{/" + loop + "}" + tail),
    ]
    tc = cell._tc
    for p in list(cell.paragraphs):
        tc.remove(p._p)
    for p in pars:
        tc.append(p._p)


def drop_numbering(p: Paragraph, center: bool = True) -> None:
    ppr = p._p.get_or_add_pPr()
    for tag in ("w:numPr", "w:pStyle", "w:ind"):
        for el in ppr.findall(qn(tag)):
            ppr.remove(el)
    if center and ppr.find(qn("w:jc")) is None:
        jc = ppr.makeelement(qn("w:jc"), {qn("w:val"): "center"})
        rpr = ppr.find(qn("w:rPr"))
        (rpr.addprevious(jc) if rpr is not None else ppr.append(jc))


# --- header: No. Dok / Hari-Tgl / meeting title (one header for the section)
h = d.sections[0].header.tables[0]
set_cell(h.rows[2].cells[3], "{noDok}")
set_cell(h.rows[3].cells[3], "{hariTgl}")
set_cell(h.rows[4].cells[0], "{judul}")

# --- Meeting Details
md = d.tables[0]
set_cell(md.rows[1].cells[1], "{judul}")
pes = md.rows[2].cells[1]
lines_block(pes, "peserta", copy.deepcopy(pes.paragraphs[0]), copy.deepcopy(pes.paragraphs[1]))
set_cell(md.rows[3].cells[1], "{lokasiMeeting}")

# --- Discussion Points: row 2 is the loop, rows 3-5 (other examples) dropped; row 6 is the original spacer row
dp = d.tables[1]
num = dp.rows[2].cells[0]
set_cell(num, "{#points}{no}.")
drop_numbering(num.paragraphs[0])
poin = dp.rows[2].cells[1]
lines_block(poin, "lines", copy.deepcopy(poin.paragraphs[0]), copy.deepcopy(poin.paragraphs[1]), tail="{/points}")
for i in (5, 4, 3):
    tr = dp.rows[i]._tr
    tr.getparent().remove(tr)

# --- Action Points: row 2 is the loop, rows 3-7 dropped
ap = d.tables[2]
row_loop(ap, 2, "actions", ["{no}.", "{rencana}", "{pic}", "{dueDate}"], drop_rows=range(3, 8))
drop_numbering(ap.rows[2].cells[0].paragraphs[0])

# --- Tanda Tangan: replaced by a raw-XML paragraph; the app builds the same table with N columns
ttd = d.tables[3]._tbl
p = copy.deepcopy(d.paragraphs[-1]._p)  # an empty body paragraph
for child in list(p):
    if child.tag != qn("w:pPr"):
        p.remove(child)
ttd.addprevious(p)
ttd.getparent().remove(ttd)
Paragraph(p, d._body).add_run("{@ttd}")

_ = _runs
save(d, out)
